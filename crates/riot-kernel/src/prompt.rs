    /// 自主性必须按后果分档，不能只写一句「不确定就问」。
    ///
    /// 裸的「不确定就问」会让模型向保守面倒：改个文件也停下来问「要继续吗」，
    /// 用户干等。拆成可逆/破坏性两档后，模型能推断没列举到的操作该归哪档。
    #[test]
