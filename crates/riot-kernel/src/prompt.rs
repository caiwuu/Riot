    /// 代码引用的格式约定必须在提示词里，而且要说清和普通代码块的区别。
    ///
    /// 只在前端实现渲染是没用的：模型不知道有这个格式就永远不会产出它，
    /// 那段渲染代码等于死代码。而不说清区别的话，它会把新写的代码也标上
    /// 行号和路径 —— 用户点开发现文件里根本不是那样。
    #[test]
